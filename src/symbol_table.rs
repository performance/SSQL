//! # Symbol Table
//!
//! The symbol table stores all declared identifiers and their vibhakti forms.
//!
//! ## Design
//!
//! - Each प्रथमा form (e.g., "छात्रः" singular, "छात्राः" plural) gets its own entry
//! - For each entry, we store all 7 vibhakti forms  
//! - Fast lookup: given any vibhakti form → find its प्रथमा base
//!
//! ## Example
//!
//! ```ignore
//! Entry for "छात्रः" (student, singular):
//!   प्रथमा: छात्रः
//!   द्वितीया: छात्रम्
//!   तृतीया: छात्रेण
//!   चतुर्थी: छात्राय
//!   पञ्चमी: छात्रात्
//!   षष्ठी: छात्रस्य
//!   सप्तमी: छात्रे
//!
//! Lookup "छात्रेण" → returns "छात्रः" with vibhakti=तृतीया, vachan=एकवचन
//! ```

use crate::types::{Linga, Vachana, Vibhakti, VibhaktiForm};
use indexmap::IndexMap;
use std::collections::HashMap;

/// A symbol table entry for one declension (singular OR plural, not both)
#[derive(Debug, Clone)]
pub struct SymbolEntry {
    /// The प्रथमा-एकवचन or प्रथमा-बहुवचन form (canonical identifier)
    pub pratipadika: String,
    
    /// Which vachan this entry represents
    pub vachana: Vachana,
    
    /// Gender of the noun
    pub linga: Linga,
    
    /// All 7 vibhakti forms for this vachan
    /// Key: Vibhakti → Value: The actual text form
    pub forms: HashMap<Vibhakti, String>,
    
    /// Source location where this was declared
    pub declared_at_line: usize,
}

impl SymbolEntry {
    pub fn new(pratipadika: String, vachana: Vachana, linga: Linga, line: usize) -> Self {
        Self {
            pratipadika,
            vachana,
            linga,
            forms: HashMap::new(),
            declared_at_line: line,
        }
    }
    
    /// Add a vibhakti form to this entry
    pub fn add_form(&mut self, vibhakti: Vibhakti, form: String) {
        self.forms.insert(vibhakti, form);
    }
    
    /// Get the form for a specific vibhakti
    pub fn get_form(&self, vibhakti: Vibhakti) -> Option<&String> {
        self.forms.get(&vibhakti)
    }
}

/// The main symbol table
/// 
/// Maintains:
/// 1. Forward map: प्रथमा form → SymbolEntry
/// 2. Reverse map: Any vibhakti form → (प्रथमा form, Vibhakti, Vachan)
pub struct SymbolTable {
    /// Map from प्रथमा base form to full symbol entry
    /// We use IndexMap to preserve declaration order
    symbols: IndexMap<String, SymbolEntry>,
    
    /// Reverse lookup: any form → its base प्रथमा + vibhakti info
    /// Example: "छात्रेण" → ("छात्रः", तृतीया, एकवचन)
    pub reverse_lookup: HashMap<String, Vec<(String, VibhaktiForm)>>,
}

impl SymbolTable {
    pub fn new() -> Self {
        Self {
            symbols: IndexMap::new(),
            reverse_lookup: HashMap::new(),
        }
    }
    
    /// Add a new symbol to the table
    /// 
    /// This should be called during Pass 1 when we encounter declarations.
    /// The caller must provide all vibhakti forms (generated by morphology engine).
    pub fn add_symbol(&mut self, entry: SymbolEntry) {
        let pratipadika = entry.pratipadika.clone();
        let vachana = entry.vachana;
        
        // Build reverse lookup for all forms
        for (vibhakti, form) in &entry.forms {
            let vib_form = VibhaktiForm::new(*vibhakti, vachana);
            
            self.reverse_lookup
                .entry(form.clone())
                .or_insert_with(Vec::new)
                .push((pratipadika.clone(), vib_form));
        }
        
        // Store the entry
        self.symbols.insert(pratipadika, entry);
    }
    
    /// Lookup a word form and get all possible interpretations
    ///
    /// Returns: Vec of (pratipadika, VibhaktiForm)
    /// - Empty vec = word not found in symbol table
    /// - Single element = unambiguous
    /// - Multiple elements = ambiguous (parser must resolve)
    pub fn lookup(&self, form: &str) -> Vec<(String, VibhaktiForm)> {
        self.reverse_lookup
            .get(form)
            .cloned()
            .unwrap_or_default()
    }
    
    /// Get a symbol entry by its प्रथमा form
    pub fn get(&self, pratipadika: &str) -> Option<&SymbolEntry> {
        self.symbols.get(pratipadika)
    }
    
    /// Check if a प्रथमा form exists
    pub fn contains(&self, pratipadika: &str) -> bool {
        self.symbols.contains_key(pratipadika)
    }
    
    /// Get all declared identifiers (in declaration order)
    pub fn all_identifiers(&self) -> Vec<&String> {
        self.symbols.keys().collect()
    }
}

impl Default for SymbolTable {
    fn default() -> Self {
        Self::new()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    
    #[test]
    fn test_symbol_table_basic() {
        let mut table = SymbolTable::new();
        
        // Create entry for "छात्रः" (student, singular, masculine)
        let mut entry = SymbolEntry::new(
            "छात्रः".to_string(),
            Vachana::Eka,
            Linga::Masculine,
            1,
        );
        
        entry.add_form(Vibhakti::Prathama, "छात्रः".to_string());
        entry.add_form(Vibhakti::Tritiya, "छात्रेण".to_string());
        entry.add_form(Vibhakti::Shashthi, "छात्रस्य".to_string());
        
        table.add_symbol(entry);
        
        // Test forward lookup
        assert!(table.contains("छात्रः"));
        
        // Test reverse lookup
        let results = table.lookup("छात्रेण");
        assert_eq!(results.len(), 1);
        assert_eq!(results[0].0, "छात्रः");
        assert_eq!(results[0].1.vibhakti, Vibhakti::Tritiya);
        assert_eq!(results[0].1.vachana, Vachana::Eka);
    }
}
