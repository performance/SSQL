    fn make_schema() -> Schema {
        // Native DDL fixture declaring table and column stems, genders, and vachanas.
        let ddl = r#"
पुस्तकानि इति पटलम् "books" इति आख्या पुस्तक इति नपुंसकलिङ्गम् बहुवचनम् रच्यताम् यत्र
    शीर्षकम् इति वाक्यम् "title" इति आख्या शीर्षक इति नपुंसकलिङ्गम् एकवचनम् च
    मूल्यम् इति वास्तविकः "price" इति आख्या मूल्य इति नपुंसकलिङ्गम् एकवचनम् च
    सङ्ख्या इति पूर्णाङ्कः "id" इति आख्या सङ्ख्या इति स्त्रीलिङ्गम् एकवचनम् च
  इति पटलम् ।
"#;
        let lexer_tokens = crate::lexer::tokenize(ddl).unwrap();
        let default_schema = Schema::default();
        let mut annotator = crate::annotator::Annotator::new().unwrap();
        let enriched = annotator.annotate(lexer_tokens, &default_schema).unwrap();
        let parser_tokens = crate::ssql_parser::convert_vibhakti_tokens(enriched);
        let ast = crate::ssql_parser::parse(parser_tokens)
            .map_err(|errors| anyhow::anyhow!("Fixture DDL parse errors: {}", errors.join("; ")))
            .unwrap();

        let mut ddl_stmts = Vec::new();
        match ast {
            crate::ast::AstNode::QueryBatch { statements, .. } => {
                for stmt in statements {
                    if let crate::ast::Statement::Ddl(ddl) = stmt {
                        ddl_stmts.push(ddl);
                    }
                }
            }
            crate::ast::AstNode::Statement(stmt) => {
                if let crate::ast::Statement::Ddl(ddl) = stmt {
                    ddl_stmts.push(ddl);
                }
            }
        }

        let mut schema = Schema::default();
        schema.update_from_ddl(&ddl_stmts, "sqlite").unwrap();
        schema
    }
    
