pub struct AstCodeGen<'a> {
    adaptor: &'a dyn SqlDialectAdaptor,
    schema: &'a Schema,
    alias_counter: usize,
    parameters: Vec<String>,
    table_aliases: HashMap<String, String>, // SQL Table Name -> Alias
    /// Physical table names already emitted as CREATE TABLE in this DDL
    /// batch. A schema may declare a table under two different Sanskrit
    /// names deliberately mapped to the same physical table (e.g. a
    /// self-referencing table given a second name so a self-join query can
    /// use two distinct words to disambiguate which side is which, since
    /// SSQL cannot otherwise tell apart two references using the identical
    /// word). Each such name resolves independently
    /// for query-time column/table resolution (handled entirely in
    /// Schema::update_from_ddl, unaffected by this set), but the physical
    /// table itself must still only be created once.
    created_tables: HashSet<String>,
    pub is_recursive_cte: bool,
    pub cycle_col: Option<Identifier>,
    pub recursive_member_idx: Option<usize>,
    pub cte_name: String,
    /// Pratipadikas of the tables actually in scope (FROM source + JOINs)
    /// for the DQL currently being generated by generate_dql_raw. Saved and
    /// restored around each call so nested subqueries don't clobber the
    /// enclosing query's scope. Used to re-derive a bare identifier's
    /// owning table without risking resolve_column's whole-schema fallback.
    active_query_tables: Vec<String>,
    /// The tables of the queries enclosing the current one, which a
    /// correlated subquery may read (`active_query_tables` of each).
    outer_query_tables: Vec<String>,
    /// Bind parameters numbered so far in the current SQL statement:
    /// PostgreSQL's placeholders are `$1..$n`, SQLite's `?`.
    pub param_count: usize,
}

impl<'a> AstCodeGen<'a> {
    pub fn new(adaptor: &'a dyn SqlDialectAdaptor, schema: &'a Schema, parameters: Vec<String>) -> Self {
        Self {
            adaptor,
            schema,
            alias_counter: 0,
            parameters,
            table_aliases: HashMap::new(),
            created_tables: HashSet::new(),
            is_recursive_cte: false,
            cycle_col: None,
            recursive_member_idx: None,
            cte_name: String::new(),
            active_query_tables: Vec::new(),
            outer_query_tables: Vec::new(),
            param_count: 0,
        }
    }

    pub fn dialect_name(&self) -> &str {
        self.adaptor.name()
    }
    
    /// Generate a unique table alias
    fn next_alias(&mut self) -> String {
        self.alias_counter += 1;
        format!("t{}", self.alias_counter)
    }

    fn get_builtin_function(&self, s_name: &str) -> Option<&str> {
        let is_postgres = self.dialect_name().to_lowercase().contains("postg");
        
        match s_name {
            // Math
            "निरपेक्षमानम्" => Some("abs"),
            "सन्निकटनम्" => Some("round"),
            "ऊर्ध्वपूर्णाङ्कः" => Some("ceil"),
            "अधःपूर्णाङ्कः" => Some("floor"),
            // SQLite gives NULL where PostgreSQL raises an error (a negative
            // root, a logarithm of 0, an arc sine beyond ±1, a remainder or
            // quotient by 0); PostgreSQL is given the same NULL.
            "वर्गमूलम्" => if is_postgres { Some("sqrt(CASE WHEN ({0}) >= 0 THEN {0} END)") } else { Some("sqrt") },
            "धनर्णचिह्नम्" => Some("sign"),
            // The operand's own brackets: arithmetic reaches a template bare.
            "ऋणात्मक" => Some("(-({0}))"),
            "ज्या" => Some("sin"),
            "कोज्या" => Some("cos"),
            "स्पर्शज्या" => Some("tan"),
            "कोटिस्पर्शज्या" => if is_postgres { Some("cot") } else { Some("(1.0 / tan({0}))") },
            // Neither dialect has cosec or sec.
            "व्युत्क्रमज्या" => Some("(1.0 / sin({0}))"),
            "व्युत्क्रमकोज्या" => Some("(1.0 / cos({0}))"),
            "चापज्या" => if is_postgres { Some("asin(CASE WHEN ({0}) BETWEEN -1 AND 1 THEN {0} END)") } else { Some("asin") },
            "चापकोज्या" => if is_postgres { Some("acos(CASE WHEN ({0}) BETWEEN -1 AND 1 THEN {0} END)") } else { Some("acos") },
            "चापस्पर्शज्या" => Some("atan"),
            "लघुगणकः" => Some("log"),
            "प्राकृतिकलघुगणकः" => if is_postgres { Some("ln(CASE WHEN ({0}) > 0 THEN {0} END)") } else { Some("ln") },
            "घाताङ्कः" => Some("exp"),
            "घातः" => Some("power"),
            "कोणांशः" => Some("degrees"),
            "चापमानम्" => Some("radians"),
            // The whole quotient; विभाज्य is the dividend (final review).
            "पूर्णलब्धिः" => if is_postgres { Some("div({0}, NULLIF({1}, 0))") } else { Some("CAST(({0}) / ({1}) AS INTEGER)") },
            // mod(), not SQLite's `%`, which truncates both operands to
            // integers (5.5 % 2 = 1); mod() is the real remainder in both
            // dialects (1.5).
            "शेषः" => if is_postgres { Some("mod({0}, NULLIF({1}, 0))") } else { Some("mod") },
            "यादृच्छिकः" => {
                if is_postgres { Some("random") } else { Some("(abs(random()) / 9223372036854775807.0)") }
            },

            // String
            "संयोजनम्" => Some("concat"),
            "खण्डः" => Some("substr"),
            // PostgreSQL has length() of text only; SQLite measures a number's text.
            "दैर्घ्यम्" => if is_postgres { Some("length(CAST({0} AS TEXT))") } else { Some("length") },
            "महावर्णरूपम्" => Some("upper"),
            "लघुवर्णरूपम्" => Some("lower"),
            "विकल्पः" => Some("coalesce"),
            "अनावृत्तम्" => Some("nullif"),
            "आद्यमहावर्णरूपम्" => Some("initcap"),
            "मार्जनम्" => Some("trim"),
            "वाममार्जनम्" => Some("ltrim"),
            "दक्षिणमार्जनम्" => Some("rtrim"),
            "प्रतिस्थापनम्" => Some("replace"),
            "स्थानम्" => {
                // PostgreSQL's `position` is not an
                // ordinary function - it only accepts the special
                // `POSITION(substring IN string)` syntax, not comma-
                // separated call arguments, so emitting `position(a, b)`
                // (this codegen's only call shape) is a syntax error.
                // `strpos(string, substring)` is an ordinary function with
                // the same call syntax AND the same (haystack, needle)
                // argument order as SQLite's `instr`, making it a true
                // drop-in replacement here.
                if is_postgres { Some("strpos") } else { Some("instr") }
            },
            "विभाजनखण्डः" => Some("split_part"),
            "पुनरावृत्तिः" => Some("repeat"),
            // As length(): PostgreSQL reverses text only.
            "विपरीतम्" => if is_postgres { Some("reverse(CAST({0} AS TEXT))") } else { Some("reverse") },
            "आदिखण्डः" => if is_postgres { Some("left") } else { Some("substr({0}, 1, {1})") },
            "अन्त्यखण्डः" => if is_postgres { Some("right") } else { Some("substr({0}, -({1}))") },

            // Dates
            "अद्यतनक्षणः" => {
                // UTC to the second on both (PostgreSQL's now() is local,
                // with a zone and microseconds).
                if is_postgres { Some("date_trunc('second', now() AT TIME ZONE 'UTC')") } else { Some("datetime('now')") }
            },
            "अद्यतनदिनाङ्कः" => {
                if is_postgres { Some("CAST(now() AT TIME ZONE 'UTC' AS DATE)") } else { Some("date('now')") }
            },
            "अद्यतनसमयः" => {
                if is_postgres { Some("CAST(date_trunc('second', CAST(now() AT TIME ZONE 'UTC' AS TIME)) AS TIME)") } else { Some("time('now')") }
            },
            "दिनाङ्कः" => if is_postgres { Some("CAST({0} AS DATE)") } else { Some("date") },
            // Whole seconds, dropped not rounded, as SQLite's functions do. The
            // time of a date (a DATE column, or date-only text) is midnight;
            // PostgreSQL refuses to cast either to a TIME directly.
            "समयः" => if is_postgres { Some("CAST(date_trunc('second', CAST(CAST({0} AS TEXT) || CASE WHEN CAST({0} AS TEXT) LIKE '%:%' THEN '' ELSE ' 00:00:00' END AS TIME)) AS TIME)") } else { Some("time") },
            "दिनाङ्कसमयः" => if is_postgres { Some("date_trunc('second', CAST({0} AS TIMESTAMP))") } else { Some("datetime") },
            "युगसमयः" => if is_postgres { Some("CAST(FLOOR(EXTRACT(EPOCH FROM CAST({0} AS TIMESTAMP))) AS BIGINT)") } else { Some("unixepoch") },
            "प्ररूपितकालः" => Some("strftime"),
            // Whole days from the date to today, UTC, on both dialects
            // (PostgreSQL's age() was an interval, SQLite's julianday a
            // fraction, and CURRENT_DATE is local).
            "अन्तरम्" => {
                if is_postgres { Some("(CAST(now() AT TIME ZONE 'UTC' AS DATE) - CAST({0} AS DATE))") } else { Some("CAST(julianday(date('now')) - julianday(date({0})) AS INTEGER)") }
            },
            // Date parts: each dialect's `emit_date_part`, an integer.
            "वर्षम्" => Some("YEAR"),
            "मासः" => Some("MONTH"),
            "दिनम्" => Some("DAY"),

            // Aggregates
            "योगः" => Some("SUM"),
            "गणना" => Some("COUNT"),
            "माध्यम्" => Some("AVG"),
            "महत्तमम्" => Some("MAX"),
            "लघुतमम्" => Some("MIN"),

            _ => None,
        }
    }

    /// A built-in with no equivalent in this dialect, as the SQL name and the
    /// dialect: it is a compile error rather than SQL that fails to run.
    fn unavailable_builtin(&self, name: &str) -> Option<(&'static str, &'static str)> {
        let postgres = self.dialect_name() == "postgres";
        match name {
            "आद्यमहावर्णरूपम्" if !postgres => Some(("INITCAP", "SQLite")),
            "विपरीतम्" if !postgres => Some(("REVERSE", "SQLite")),
            "पुनरावृत्तिः" if !postgres => Some(("REPEAT", "SQLite")),
            "विभाजनखण्डः" if !postgres => Some(("SPLIT_PART", "SQLite")),
            // strftime's format codes are SQLite's own.
            "प्ररूपितकालः" if postgres => Some(("STRFTIME", "PostgreSQL")),
            _ => None,
        }
    }

    fn check_available(&self, name: &str) -> Result<()> {
        if let Some((sql, dialect)) = self.unavailable_builtin(name) {
            anyhow::bail!("`{}` ({}) has no equivalent in {}, so this query cannot be compiled for it", name, sql, dialect);
        }
        Ok(())
    }

    /// A sort key in one order on both dialects: text by byte value, as
    /// SQLite sorts it, where PostgreSQL would use the database's collation
    /// (`कालिदास` before `Amartya` on one, after on the other).
    fn sort_key(&self, sql: String, expr: &Expression, table_context: Option<&str>) -> String {
        let text = self.resolve_expr_sql_type(expr, table_context).map_or(false, |t| t.eq_ignore_ascii_case("text"));
        if self.dialect_name() == "postgres" && text {
            format!("{} COLLATE \"C\"", sql)
        } else {
            sql
        }
    }

    /// The separator closing each id on a recursive CTE's path column: the
    /// unit separator, which no id contains. Both dialects cut a cycle with
    /// the same exact search of the path; PostgreSQL's CYCLE clause instead
    /// kept the row that closes the cycle.
    fn path_separator(&self) -> &'static str {
        if self.dialect_name() == "postgres" { "chr(31)" } else { "CHAR(31)" }
    }

    fn translate_function_name(&self, s_name: &str) -> String {
        let stem = s_name
            .trim_end_matches("म्")
            .trim_end_matches('ं')
            .trim_end_matches('ः')
            .to_string();
        
        if let Some(sql_name) = self.schema.functions.get(s_name) {
            return sql_name.to_string();
        }
        if let Some(sql_name) = self.schema.functions.get(&stem) {
            return sql_name.to_string();
        }
        
        // A built-in is called by its inflected name only; a bare stem is
        // not a word (expert review P1b).
        if let Some(sql_name) = self.get_builtin_function(s_name) {
            return sql_name.to_string();
        }

        s_name.to_string()
    }

    /// The built-in name to write instead of `word`: the inflected name of a
    /// bare stem (`वर्गमूल` → `वर्गमूलम्`), or the one name kept for a
    /// function that had several (expert review Q7b).
    fn builtin_form_of_stem(&self, word: &str) -> Option<String> {
        if let Some((_, kept)) = RETIRED_FUNCTION_NAMES.iter().find(|(old, _)| *old == word) {
            return Some(format!("`{}` is no longer a function name; the function is `{}`", word, kept));
        }
        [format!("{}म्", word), format!("{}ः", word)]
            .into_iter()
            .find(|form| self.get_builtin_function(form).is_some())
            .map(|form| format!("`{}` is a bare stem, not a word; write `{}`", word, form))
    }

    fn is_known_function(&self, name: &str) -> bool {
        let stem = name
            .trim_end_matches("म्")
            .trim_end_matches('ं')
            .trim_end_matches('ः');
        self.schema.functions.contains_key(name)
            || self.schema.functions.contains_key(stem)
            || self.get_builtin_function(name).is_some()
    }

    fn format_function_template(&self, template: &str, args: &[String]) -> String {
        let mut result = template.to_string();
        if result.contains("{0}") || result.contains("{1}") {
            for (i, arg) in args.iter().enumerate() {
                let placeholder = format!("{{{}}}", i);
                result = result.replace(&placeholder, arg);
            }
        } else if result.contains("{}") {
            if !args.is_empty() {
                result = result.replace("{}", &args[0]);
            }
        }
        result
    }

    /// Generate SQL from a DQL statement (Raw, no semicolon)
    pub fn generate_dql_raw(&mut self, stmt: &DqlStatement) -> Result<String> {
        let mut sql_parts = Vec::new();
        // Saved/restored (not just cleared) for the same reason as
        // active_query_tables below: a nested subquery's own call to this
        // function must not permanently clobber the enclosing query's alias
        // map. Without this, a bare column resolved (correctly, via the
        // scoped lookup below) to a JOINed table whose codegen happens
        // *after* a WHERE-clause subquery - e.g. an ORDER BY - would look up
        // that table's alias in a map the subquery had already overwritten
        // with its own, and silently fall back to the wrong alias instead
        // of erroring or resolving correctly.
        //
        // The nested scope starts as a copy of the enclosing one (not empty):
        // a correlated subquery may name the outer query's tables
        // (`… पुस्तकस्य सङ्ख्या …` inside an EXISTS over sale_items), which must
        // resolve to the outer alias (t1.id), never to the bare table name,
        // which SQL rejects once the table is aliased. The subquery's own
        // FROM/JOIN tables still shadow outer ones of the same name.
        let prev_table_aliases = self.table_aliases.clone();

        // ---------------------------------------------------------
        // 1. Alias Population Phase (Pre-scan)
        // ---------------------------------------------------------

        // Source
        let source_sql_name = self.resolve_table(&stmt.source.table)?; // SQL Name
        let source_stem = self.resolve_table_stem(&stmt.source.table); // Stem
        let source_alias = self.next_alias();
        self.table_aliases.insert(source_stem.clone(), source_alias.clone());

        // Joins (Populate Map)
        let mut query_tables = vec![source_stem.clone()];
        for join in &stmt.joins {
             let join_stem = self.resolve_table_stem(&join.table);
             let join_alias = self.next_alias();
             self.table_aliases.insert(join_stem.clone(), join_alias);
             query_tables.push(join_stem);
        }
        // Saved/restored (not just overwritten) so a nested subquery's own
        // scope doesn't leak into - or clobber - the enclosing query's once
        // the nested call returns.
        let prev_active_query_tables = std::mem::replace(&mut self.active_query_tables, query_tables);
        let prev_outer_len = self.outer_query_tables.len();
        self.outer_query_tables.extend(prev_active_query_tables.iter().cloned());

        // ---------------------------------------------------------
        // 2. Generation Phase
        
        // A. Select Clause (Now all aliases are available)
        // Use source stem as default context
        let table_context = Some(stmt.source.table.pratipadika.as_str());
        
        // Pass source alias as default context? No, just rely on table_context and resolve_column
        let mut columns = self.generate_select(&stmt.select.columns, Some(&source_alias), table_context)?;
        if self.is_recursive_cte {
            if let Some(ref c_col) = self.cycle_col {
                let resolved_col = self.schema.resolve_column(&c_col.text, table_context)
                    .map(|(name, _, _)| name.to_string())
                    .unwrap_or_else(|| c_col.text.clone());
                if let Some(0) = self.recursive_member_idx {
                    columns.push(crate::codegen::traits::ColumnExpr {
                        expr: format!("{sep} || {}.{} || {sep}", source_alias, resolved_col, sep = self.path_separator()),
                        alias: Some("path".to_string()),
                    });
                } else if let Some(1) = self.recursive_member_idx {
                    let cte_alias = self.table_aliases.iter()
                        .find(|(k, _)| k.contains(&self.cte_name) || self.cte_name.contains(*k))
                        .map(|(_, v)| v.clone())
                        .unwrap_or_else(|| "path".to_string());
                    // Every id is closed by its own separator, as the
                    // anchor's is, so the cycle guard finds any id on
                    // the path, not only the root (`|1|2|3|`, not `|1|23`).
                    columns.push(crate::codegen::traits::ColumnExpr {
                        expr: format!("{}.path || {}.{} || {}", cte_alias, source_alias, resolved_col, self.path_separator()),
                        alias: Some("path".to_string()),
                    });
                }
            }
        }
        let distinct = stmt.select.distinct;
        sql_parts.push(self.adaptor.emit_select(&columns, distinct));
        
        // B. From Clause
        let table_ref = TableRef {
            table_name: source_sql_name,
            alias: source_alias.clone(),
        };
        sql_parts.push(self.adaptor.emit_from(&table_ref));

        // C. Joins (Generate SQL)
        for join in &stmt.joins {
             // Resolve again
             let join_table_name = self.resolve_table(&join.table)?;
             let join_stem = self.resolve_table_stem(&join.table);
             
             // Retrieve Alias (Must exist)
             let join_alias = self.table_aliases.get(&join_stem).cloned().unwrap_or_else(|| "MISSING_ALIAS".to_string());
             
             let join_condition = if let Some(cond) = &join.condition {
                 self.generate_expression(cond, None, None)?
             } else {
                 "1=1".to_string()
             };

             let join_type = match join.join_type {
                 Some(crate::ast::JoinType::Left) => crate::codegen::traits::JoinType::Left,
                 Some(crate::ast::JoinType::Right) => crate::codegen::traits::JoinType::Right,
                 Some(crate::ast::JoinType::Full) => crate::codegen::traits::JoinType::Full,
                 Some(crate::ast::JoinType::Cross) => crate::codegen::traits::JoinType::Cross,
                 None => crate::codegen::traits::JoinType::Inner,
             };
             
             let join_expr = crate::codegen::traits::JoinExpr {
                 join_type,
                 table: TableRef {
                     table_name: join_table_name,
                     alias: join_alias,
                 },
                 condition: join_condition,
             };
             
             sql_parts.push(self.adaptor.emit_join(&join_expr));
        }
        
        // 5. Where Clause (optional)
        let mut where_sql = String::new();
        if let Some(ref where_clause) = stmt.where_clause {
            where_sql = self.generate_expression(&where_clause.condition, Some(&source_alias), table_context)?;
        }
        if self.is_recursive_cte {
            if let Some(ref c_col) = self.cycle_col {
                if let Some(1) = self.recursive_member_idx {
                    let resolved_col = self.schema.resolve_column(&c_col.text, table_context)
                        .map(|(name, _, _)| name.to_string())
                        .unwrap_or_else(|| c_col.text.clone());
                    let cte_alias = self.table_aliases.iter()
                        .find(|(k, _)| k.contains(&self.cte_name) || self.cte_name.contains(*k))
                        .map(|(_, v)| v.clone())
                        .unwrap_or_else(|| "path".to_string());
                    // An exact search: LIKE read `%` and `_` in a text id as
                    // wildcards, and on PostgreSQL (ILIKE) ignored case.
                    let find = if self.dialect_name() == "postgres" { "strpos" } else { "instr" };
                    let cycle_cond = format!("{find}({}.path, {sep} || {}.{} || {sep}) = 0", cte_alias, source_alias, resolved_col, sep = self.path_separator());
                    if where_sql.is_empty() {
                        where_sql = cycle_cond;
                    } else {
                        where_sql = format!("({}) AND {}", where_sql, cycle_cond);
                    }
                }
            }
        }
        if !where_sql.is_empty() {
            sql_parts.push(self.adaptor.emit_where(&where_sql));
        }

        // GROUP BY
        if let Some(ref group_by) = stmt.group_by {
            let exprs: Result<Vec<String>> = group_by.expressions.iter()
                .map(|e| self.generate_expression(e, Some(&source_alias), table_context))
                .collect();
            sql_parts.push(format!("GROUP BY {}", exprs?.join(", ")));
        }

        // HAVING
        if let Some(ref having) = stmt.having {
            let condition = self.generate_expression(&having.condition, Some(&source_alias), table_context)?;
            sql_parts.push(format!("HAVING {}", condition));
        }

        // ORDER BY
        if let Some(ref order_by) = stmt.order_by {
            let os: Result<Vec<String>> = order_by.items.iter()
                .map(|item| {
                    let expr_sql = self.generate_expression(&item.expr, Some(&source_alias), table_context)?;
                    let dir_sql = match item.direction {
                        crate::ast::OrderDirection::Asc => "ASC",
                        crate::ast::OrderDirection::Desc => "DESC",
                    };
                    // SQLite sorts NULL first ascending, PostgreSQL last; SSQL
                    // defines one order (missing values last) for every dialect.
                    Ok(format!("{} {} NULLS LAST", self.sort_key(expr_sql, &item.expr, table_context), dir_sql))
                })
                .collect();
             sql_parts.push(format!("ORDER BY {}", os?.join(", ")));
        }

        // LIMIT
        if let Some(ref limit) = stmt.limit {
            let limit_sql = self.generate_expression(&limit.count, None, None)?;
            let mut limit_part = format!("LIMIT {}", limit_sql);
            
            if let Some(ref offset) = limit.offset {
                 let offset_sql = self.generate_expression(offset, None, None)?;
                 limit_part.push_str(&format!(" OFFSET {}", offset_sql));
            }
            sql_parts.push(limit_part);
        }

        self.active_query_tables = prev_active_query_tables;
        self.outer_query_tables.truncate(prev_outer_len);
        self.table_aliases = prev_table_aliases;
        Ok(sql_parts.join("\n"))
    }

    /// Generate SQL from a DQL statement (Statement, with semicolon)
    pub fn generate_dql(&mut self, stmt: &DqlStatement) -> Result<String> {
        let sql = self.generate_dql_raw(stmt)?;
        Ok(format!("{};\n", sql))
    }
    
    /// Convert Devanagari digits to Arabic numerals
    fn convert_numerals(text: &str) -> String {
        text.replace('०', "0")
            .replace('१', "1")
            .replace('२', "2")
            .replace('३', "3")
            .replace('४', "4")
            .replace('५', "5")
            .replace('६', "6")
            .replace('७', "7")
            .replace('८', "8")
            .replace('९', "9")
    }

    /// Returns true if `s` is an ISO-8601 date, time, or timestamp literal
    /// (allowing either Devanagari ०-९ or ASCII 0-9 digits) so Devanagari
    /// date strings like `"२०२३-१०-०१"` normalize to `'2023-10-01'` in SQL.
    fn is_date_or_time_literal(s: &str) -> bool {
        let trimmed = s.trim();
        !trimmed.is_empty()
            && (trimmed.contains('-') || trimmed.contains(':'))
            && trimmed.chars().any(|c| ('०'..='९').contains(&c))
            && trimmed.chars().all(|c| {
                c.is_ascii_digit()
                    || ('०'..='९').contains(&c)
                    || matches!(c, '-' | ':' | ' ' | 'T' | 'Z' | '.' | '+')
            })
    }
    
    /// Resolve a Sanskrit table identifier to its Pratipadika (Stem) for aliasing
    /// Generates an UPDATE's or DELETE's clauses with its own table as the
    /// query's: a column of another table is an error, not that table's SQL
    /// name (`UPDATE books SET price = quantity` read the inventory's).
    fn in_table_scope<T>(&mut self, stem: &str, f: impl FnOnce(&mut Self) -> Result<T>) -> Result<T> {
        let prev = std::mem::replace(&mut self.active_query_tables, vec![stem.to_string()]);
        let prev_outer_len = self.outer_query_tables.len();
        self.outer_query_tables.extend(prev.iter().cloned());
        let result = f(self);
        self.active_query_tables = prev;
        self.outer_query_tables.truncate(prev_outer_len);
        result
    }

    /// A required (`अनिवार्य`) or key (`प्राथमिक`) column always holds a
    /// value: emptying it fails at run time on every database.
    fn check_may_be_empty(&self, column: &Identifier, table: &str) -> Result<()> {
        for candidate in [column.text.as_str(), column.pratipadika.as_str()] {
            if let Some((sql_name, _, owner)) = self.schema.resolve_column(candidate, Some(table)) {
                if self.schema.required_columns.contains(&(owner.to_string(), sql_name.to_string())) {
                    bail!(
                        "`{}` is declared required (`अनिवार्य`) or a key (`प्राथमिक`), so it always holds a value and cannot be made empty (`रिक्त-`)",
                        column.text
                    );
                }
                return Ok(());
            }
        }
        Ok(())
    }

    fn resolve_table_stem(&self, ident: &Identifier) -> String {
        // Try original Sanskrit pratipadika first
        if !ident.pratipadika.is_empty() && ident.pratipadika != ident.text {
            return ident.pratipadika.clone();
        }
        // Try schema resolution first
        if let Some(stem) = self.schema.resolve_pratipadika(&ident.text) {
            return stem.to_string();
        }
        // Fallback to text
        ident.text.clone()
    }

    /// Resolve a Sanskrit table identifier to SQL table name
    /// Tries: inflected form first, then pratipadika (Prathama base form)
    fn resolve_table(&self, ident: &Identifier) -> Result<String> {
        // Try inflected form first (e.g., पुस्तकेभ्यः)
        if let Some(sql_name) = self.schema.resolve_table(&ident.text) {
            return Ok(sql_name.to_string());
        }
        
        // Try pratipadika (base form, e.g., पुस्तकानि)
        if let Some(sql_name) = self.schema.resolve_table(&ident.pratipadika) {
            return Ok(sql_name.to_string());
        }

        // Hard-error if the table reference cannot be resolved against the
        // schema so that mismatched table stems or genders surface at compile time.
        bail!(
            "Cannot resolve table reference '{}' (stem: '{}') against the schema - \
             check the table's declared gender/stem match how it's inflected here",
            ident.text,
            ident.pratipadika
        )
    }

    /// Resolve a Sanskrit table identifier to its declared primary-key
    /// column's SQL name, for FOREIGN KEY codegen. Resolved dynamically
    /// rather than hardcoded to the literal string "id", since not every
    /// referenced table actually calls its primary key that. Falls back to
    /// "id" only if the referenced table truly has no declared primary key
    /// on record, to avoid emitting no REFERENCES target at all.
    fn resolve_table_pk(&self, ident: &Identifier) -> String {
        if let Some(pk) = self.schema.resolve_table_primary_key(&ident.text) {
            return pk.to_string();
        }
        if let Some(pk) = self.schema.resolve_table_primary_key(&ident.pratipadika) {
            return pk.to_string();
        }
        "id".to_string()
    }

    /// Resolve a Sanskrit column identifier to (SQL column name, owning
    /// table's pratipadika, if determinable). Same inflected-then-
    /// pratipadika lookup order as resolve_column, but also surfaces which
    /// table schema resolution found the column in - needed so a bare
    /// identifier in a multi-table JOIN can be stamped with the alias of
    /// the table that actually declares it, rather than the
    /// Expression::Identifier codegen arm's own single primary-table alias
    /// passed down through the whole expression tree - a bare column in a
    /// multi-table JOIN can belong to any of the joined tables, not just
    /// the primary one.
    fn resolve_column_with_table(&self, ident: &Identifier, table_context: Option<&str>) -> Result<(String, Option<String>)> {
        // Prefer scoping to the tables actually joined in this query
        // before ever risking resolve_column's own
        // table_context fallthrough, which silently searches the whole
        // schema.सं when the column isn't on that one table - in a large
        // shared schema with column-name reuse across unrelated tables,
        // that can return the wrong table's column or go needlessly
        // ambiguous even though the query's own JOINs unambiguously settle it.
        if !self.active_query_tables.is_empty() {
            // Try the inflected surface form first, then the bare
            // pratipadika - same two-step order as the old `.or_else`
            // chain. Bail immediately on the first `Ambiguous` result
            // rather than trying the other form or falling through: a
            // column genuinely ambiguous between 2+ of the query's own
            // JOINed tables must be a hard error, never
            // silently resolved by privileging whichever table happens to
            // be `table_context` (usually the primary FROM-source) below.
            for candidate in [ident.text.as_str(), ident.pratipadika.as_str()] {
                match self.schema.resolve_column_in_tables(candidate, &self.active_query_tables) {
                    ScopedColumn::Found((sql_name, _, table)) => {
                        return Ok((sql_name.to_string(), Some(table.to_string())));
                    }
                    ScopedColumn::Ambiguous(mut tables) => {
                        tables.sort();
                        tables.dedup();
                        bail!(
                            "Column '{}' is ambiguous between JOINed tables {} - qualify it with a genitive (e.g. '<table-name>स्य {}') to disambiguate",
                            ident.text,
                            tables.join(", "),
                            ident.text
                        );
                    }
                    ScopedColumn::NotFound => {}
                }
            }
        }

        // Outside the query's own tables the column may only come from an
        // enclosing query's (a correlated subquery); a whole-schema match on
        // some other table used to be taken, so a CTE's unselected column
        // read the base table's (`WITH c AS (SELECT title …) SELECT price FROM c`).
        let in_scope = |table: &str| {
            self.active_query_tables.is_empty()
                || self.active_query_tables.iter().chain(&self.outer_query_tables).any(|t| t == table)
        };
        for candidate in [ident.text.as_str(), ident.pratipadika.as_str()] {
            if let Some((sql_name, _, table)) = self.schema.resolve_column(candidate, table_context) {
                if in_scope(table) {
                    return Ok((sql_name.to_string(), Some(table.to_string())));
                }
                bail!(
                    "`{}` is not a column of any table this statement reads ({}); it belongs to `{}`",
                    self.column_word(table, sql_name),
                    self.active_query_tables.join(", "),
                    table
                );
            }
        }
        // Hard-error if a bare column reference in a multi-table query fails
        // to resolve against any table in scope or the schema.
        if let Some(form) = self.builtin_form_of_stem(&ident.text) {
            bail!("{}", form);
        }
        bail!(
            "Cannot resolve column reference '{}' (stem: '{}'){} against the schema",
            ident.text,
            ident.pratipadika,
            table_context.map(|t| format!(" in table context '{}'", t)).unwrap_or_default()
        )
    }

    /// The SQL name of `field`, a column of `table` itself.
    fn qualified_column(&self, field: &Identifier, table: &str) -> Result<String> {
        for candidate in [field.text.as_str(), field.pratipadika.as_str()] {
            if let ScopedColumn::Found((sql_name, _, _)) = self.schema.resolve_column_in_tables(candidate, &[table.to_string()]) {
                return Ok(sql_name.to_string());
            }
        }
        if let Some((sql_name, _, owner)) = self.schema.resolve_column(&field.text, Some(table)) {
            bail!("`{}` is not a column of `{}`; it belongs to `{}`", self.column_word(owner, sql_name), table, owner);
        }
        self.resolve_column(field, Some(table))
    }

    /// A column's Sanskrit nominative from its SQL name, for messages: an
    /// earlier pass has already put the SQL name in the identifier.
    fn column_word(&self, table: &str, sql_name: &str) -> String {
        self.schema.tables.get(table)
            .and_then(|t| t.fields.values().find(|c| c.sql_name == sql_name))
            .and_then(|c| {
                let mut m = crate::morphology::MorphologyEngine::new().ok()?;
                m.decline_with_gender(&c.pratipadika, c.gender, crate::types::Vachana::Eka).ok()?
                    .forms.get(&crate::types::Vibhakti::Prathama).cloned()
            })
            .unwrap_or_else(|| sql_name.to_string())
    }

    /// Resolve a Sanskrit column identifier to SQL column name
    /// Tries: inflected form first, then pratipadika (Prathama base form)
    fn resolve_column(&self, ident: &Identifier, table_context: Option<&str>) -> Result<String> {
        // Try inflected form first
        if let Some((sql_name, _, _)) = self.schema.resolve_column(&ident.text, table_context) {
            return Ok(sql_name.to_string());
        }

        // Try pratipadika
        if let Some((sql_name, _, _)) = self.schema.resolve_column(&ident.pratipadika, table_context) {
            return Ok(sql_name.to_string());
        }

        // Hard-error if the column reference cannot be resolved against the schema.
        if let Some(form) = self.builtin_form_of_stem(&ident.text) {
            bail!("{}", form);
        }
        bail!(
            "Cannot resolve column reference '{}' (stem: '{}'){} against the schema",
            ident.text,
            ident.pratipadika,
            table_context.map(|t| format!(" in table context '{}'", t)).unwrap_or_default()
        )
    }

    /// Resolve the declared SQL type (e.g. "text", "date") of a column-like
    /// expression, if determinable. Used by date-part extraction
    /// to decide whether PostgreSQL needs an explicit cast before
    /// TO_CHAR - unlike resolve_column, failure here just means "unknown",
    /// not a compile error, since not every expression shape is a column.
    fn resolve_expr_sql_type(&self, expr: &Expression, table_context: Option<&str>) -> Option<String> {
        match expr {
            Expression::Identifier(ident) => {
                self.schema.resolve_column(&ident.text, table_context)
                    .or_else(|| self.schema.resolve_column(&ident.pratipadika, table_context))
                    .map(|(_, sql_type, _)| sql_type.to_string())
            }
            Expression::FieldAccess { object, field } => {
                if let Expression::Identifier(obj_ident) = object.as_ref() {
                    let table_stem = self.resolve_table_stem(obj_ident);
                    return self.schema.resolve_column(&field.text, Some(&table_stem))
                        .map(|(_, sql_type, _)| sql_type.to_string());
                }
                None
            }
            _ => None,
        }
    }

    /// A condition read as a value (a selected value, an aggregate's
    /// argument) is 1 or 0 on both dialects; PostgreSQL's is a boolean
    /// (`t`/`f`), which SUM refuses.
    fn condition_as_value(&self, expr: &Expression, sql: String) -> String {
        use crate::ast::BinaryOperator::*;
        let condition = match expr {
            Expression::BinaryOp { op, .. } | Expression::SanskritComparison { op, .. } => !matches!(op, Add | Subtract | Multiply | Divide),
            Expression::LogicalOp { .. } | Expression::Between { .. } | Expression::Exists { .. } => true,
            _ => false,
        };
        if condition && self.dialect_name() == "postgres" {
            format!("CAST(({}) AS INTEGER)", sql)
        } else {
            sql
        }
    }

    /// Generate SELECT column expressions
    fn generate_select(&mut self, columns: &[crate::ast::SelectItem], table_alias: Option<&str>, table_context: Option<&str>) -> Result<Vec<ColumnExpr>> {
        let mut result = Vec::new();
        
        for col in columns {
            let expr_str = self.generate_expression(&col.expr, table_alias, table_context)?;
            let expr_str = self.condition_as_value(&col.expr, expr_str);
            if let Some(alias) = &col.alias {
                // A query-level `इति "alias"` string is just as user-controlled
                // as a schema आख्या and reaches the same unescaped `AS <alias>`
                // codegen position - see schema::validate_sql_identifier.
                crate::schema::validate_sql_identifier(alias, "a SELECT item's इति \"...\" alias")?;
            }
            result.push(ColumnExpr {
                expr: expr_str,
                alias: col.alias.clone(),
            });
        }
        Ok(result)
    }




    /// Generate SQL expression from AST Expression
    pub fn generate_expression(&mut self, expr: &Expression, table_alias: Option<&str>, table_context: Option<&str>) -> Result<String> {
        match expr {
            Expression::FieldAccess { object, field } => {
                // A field name can legitimately collide with a known builtin
                // function name (e.g. "समय"/"समयः" also maps to SQL `time`)
                // while still being an ordinary, real schema column of
                // object's table. Without this check, "X.समयः" - a real
                // column reference - would be unconditionally reinterpreted
                // as "time(X)", a function call, discarding the fact that
                // the AST had already correctly resolved it as a Column
                // earlier in the pipeline. A genuine schema column match must
                // always win over the builtin-function reinterpretation,
                // which exists for the separate "X's UPPER"-style natural
                // unary-function-call phrasing - only fall back to treating
                // the field as a function name when it does NOT resolve as
                // a real column here.
                let is_real_column = if let Expression::Identifier(ident) = object.as_ref() {
                    let table_stem = self.resolve_table_stem(ident);
                    self.schema.resolve_column(&field.text, Some(&table_stem)).is_some()
                        || self.schema.resolve_column(&field.pratipadika, Some(&table_stem)).is_some()
                } else {
                    false
                };

                let s_name = &field.text;
                if !is_real_column && self.is_known_function(s_name) {
                    self.check_available(s_name)?;
                    let mut obj_clone = (**object).clone();
                    if let Expression::Identifier(ref mut id) = obj_clone {
                        if self.schema.resolve_table(&id.pratipadika).is_none()
                            && self.schema.resolve_table(&id.text).is_none()
                        {
                            id.symbol_type = crate::types::SymbolType::Column;
                        }
                    }
                    let arg_sql = self.generate_expression(&obj_clone, table_alias, table_context)?;
                    let trans_name = self.translate_function_name(s_name);
                    if matches!(trans_name.as_str(), "YEAR" | "MONTH" | "DAY") {
                        let arg_sql_type = self.resolve_expr_sql_type(&obj_clone, table_context);
                        return Ok(self.adaptor.emit_date_part(&trans_name, &arg_sql, arg_sql_type.as_deref()));
                    }
                    if trans_name.contains("{}") || trans_name.contains("{0}") {
                        return Ok(self.format_function_template(&trans_name, &[arg_sql]));
                    } else {
                        return Ok(format!("{}({})", trans_name, arg_sql));
                    }
                }

                if let Expression::Identifier(ident) = object.as_ref() {
                    // RESOLVE TABLE REFERENCE USING STEM FOR ALIAS LOOKUP
                    let table_stem = self.resolve_table_stem(ident);
                    
                    if let Some(alias) = self.table_aliases.get(&table_stem) {
                         // The qualifier names the one table the column is
                         // of (`सुलभस्य मूल्यम्`); a whole-schema match on
                         // another table used to be taken.
                         let col_sql = self.qualified_column(field, &table_stem)?;
                         return Ok(format!("{}.{}", alias, col_sql));
                    }
                    
                    // Fallback to direct SQL table name lookup (if no alias found?)
                    if let Some(sql_table_name) = self.schema.resolve_table(&ident.text) {
                         let col_sql = self.resolve_column(field, Some(&table_stem))?;
                         return Ok(format!("{}.{}", sql_table_name, col_sql));
                    }
                }
                
                // Fallback
                let obj_sql = self.generate_expression(object, None, None)?;
                let field_sql = self.resolve_column(field, None)?;
                Ok(format!("{}.{}", obj_sql, field_sql))
            }

            Expression::Identifier(ident) => {
                // 1. Check if it's an external parameter (BAHYA) or raw placeholder
                if ident.text == "?" || self.parameters.contains(&ident.text) || self.parameters.contains(&ident.pratipadika) {
                    if self.dialect_name() == "postgres" {
                        self.param_count += 1;
                        return Ok(format!("${}", self.param_count));
                    }
                    return Ok("?".to_string());
                }

                if ident.symbol_type == crate::types::SymbolType::Variable || ident.symbol_type == crate::types::SymbolType::Table {
                    return Ok(format!("(SELECT * FROM {})", ident.text));
                }
                
                // 2. Special Case: Standalone "GANANA" (Count) requires explicit wildcard
                if ident.pratipadika == "गणन" || ident.text == "गणना" {
                }

                let (col_name, owning_table) = self.resolve_column_with_table(ident, table_context)?;

                // Prefer the alias of the table schema resolution actually
                // found this column in, over the single primary-table
                // alias passed down through the whole expression tree.
                // Only takes effect when that table
                // differs from - or isn't captured by - table_alias, so
                // single-table queries (the common case) are unaffected.
                if let Some(owner) = owning_table {
                    if let Some(alias) = self.table_aliases.get(&owner) {
                        return Ok(format!("{}.{}", alias, col_name));
                    }
                }

                if let Some(alias) = table_alias {
                    Ok(format!("{}.{}", alias, col_name))
                } else {
                    Ok(col_name)
                }
            }
            
            Expression::Literal(lit) => match lit {
                Literal::Number(n) => Ok(Self::convert_numerals(n)),
                Literal::String(s) => {
                    let normalized = if Self::is_date_or_time_literal(s) {
                        Self::convert_numerals(s)
                    } else {
                        s.clone()
                    };
                    Ok(format!("'{}'", normalized.replace("'", "''")))
                }
                Literal::Null => Ok("NULL".to_string()),
            },
            
            Expression::BinaryOp { left, op, right } => {
                let left_sql = self.generate_expression(left, table_alias, table_context)?;
                
                if *op == BinaryOperator::In || *op == BinaryOperator::NotIn {
                    // Unwind right expression (LogicalOp chain)
                    fn collect_in_values<'a>(expr: &'a Expression, list: &mut Vec<&'a Expression>) {
                        if let Expression::LogicalOp { left, op, right } = expr {
                            if *op == LogicalOperator::And {
                                collect_in_values(left, list);
                                collect_in_values(right, list);
                                return;
                            }
                        }
                        list.push(expr);
                    }
                    
                    let mut items: Vec<&Expression> = Vec::new();
                    collect_in_values(right, &mut items);
                    
                    let mut val_sqls = Vec::new();
                    for item in &items {
                         val_sqls.push(self.generate_expression(item, table_alias, table_context)?);
                    }
                    
                    let not = if *op == BinaryOperator::NotIn { "NOT " } else { "" };
                    // A subquery already brings its own brackets: IN (SELECT …),
                    // not IN ((SELECT …)).
                    if let [Expression::Subquery(_)] = items.as_slice() {
                        return Ok(format!("{} {}IN {}", left_sql, not, val_sqls[0]));
                    }
                    Ok(format!("{} {}IN ({})", left_sql, not, val_sqls.join(", ")))
                } else {
                    let right_sql = self.generate_expression(right, table_alias, table_context)?;
                    // The AST's grouping must survive into SQL's flat infix
                    // syntax: bracket an operand that binds more loosely than
                    // its operator (`price * (2 + 5)`), and a right operand of
                    // `-` or `/` that binds equally (`a - (b - c)`).
                    let left_sql = if arithmetic_operand_needs_parens(op, left, false) {
                        format!("({})", left_sql)
                    } else {
                        left_sql
                    };
                    let right_sql = if arithmetic_operand_needs_parens(op, right, true) {
                        format!("({})", right_sql)
                    } else {
                        right_sql
                    };
                    Ok(self.adaptor.emit_binary_op(&left_sql, &right_sql, op.clone()))
                }
            }
            
            Expression::LogicalOp { left, op, right } => {
                let left_sql = self.generate_expression(left, table_alias, table_context)?;
                let right_sql = self.generate_expression(right, table_alias, table_context)?;
                let op_str = match op {
                    LogicalOperator::And => "AND",
                    LogicalOperator::Or => "OR",
                };
                Ok(format!("({} {} {})", left_sql, op_str, right_sql))
            }
            
            Expression::Case { cases } => {
                self.generate_case(cases, table_alias, table_context)
            }
            
            Expression::FunctionCall { name, args, window, .. } => {
                self.check_available(name)?;
                let trans_name = self.translate_function_name(name);
                // A Sanskrit word that is neither an SSQL function nor a pure
                // UDF must not reach SQL as a call (e.g. `माध्यम्(t1.price)`),
                // where it only fails at run time.
                if trans_name == *name && name.chars().any(|c| ('\u{0900}'..='\u{097F}').contains(&c)) {
                    if let Some(form) = self.builtin_form_of_stem(name) {
                        anyhow::bail!("{}", form);
                    }
                    anyhow::bail!(
                        "Unknown function `{}`: it is neither an SSQL function nor a pure function (`शुद्धम् कार्यम्`)",
                        name
                    );
                }
                
                // Builtins that need more than the one value they are said of
                // (`शीर्षकस्य खण्डः` alone would emit SUBSTR(t1.title), which
                // the database rejects): require their other arguments.
                let min_args = match trans_name.to_lowercase().as_str() {
                    "replace" => 3,
                    "substr" | "power" | "mod" | "div" | "nullif" | "instr" | "strpos" => 2,
                    _ => 0,
                };
                if args.len() < min_args {
                    anyhow::bail!(
                        "`{}` ({}) needs {} arguments but was given {} (e.g. `शीर्षके १ स्थानात् आरभ्य ३ वर्णानाम् खण्डः` for SUBSTR)",
                        name, trans_name.to_uppercase(), min_args, args.len()
                    );
                }

                // Special handling for Dialect-specific functions (e.g. Date parts)
                if (trans_name == "MONTH" || trans_name == "YEAR" || trans_name == "DAY" || trans_name == "HOUR" || trans_name == "MINUTE" || trans_name == "SECOND" || trans_name == "DAYNAME") && args.len() == 1 {
                    let arg_sql = self.generate_expression(&args[0], table_alias, table_context)?;
                    let arg_sql_type = self.resolve_expr_sql_type(&args[0], table_context);
                    return Ok(self.adaptor.emit_date_part(&trans_name, &arg_sql, arg_sql_type.as_deref()));
                }

                let ordered_args_cow: Vec<Expression> = if args.iter().any(|a| matches!(a, Expression::NamedArg { .. })) {
                    let stem = name
                        .trim_end_matches("म्")
                        .trim_end_matches('ं')
                        .trim_end_matches('ः');
                    if let Some(expected_params) = self
                        .schema
                        .udf_params
                        .get(name)
                        .or_else(|| self.schema.udf_params.get(stem))
                    {
                        let mut ordered = Vec::with_capacity(expected_params.len());
                        for expected_stem in expected_params {
                            let found = args.iter().find_map(|a| {
                                if let Expression::NamedArg { param, value } = a {
                                    let p_stem = param
                                        .pratipadika
                                        .trim_end_matches("म्")
                                        .trim_end_matches('ं')
                                        .trim_end_matches('ः');
                                    let p_text_stem = param
                                        .text
                                        .trim_end_matches("म्")
                                        .trim_end_matches('ं')
                                        .trim_end_matches('ः');
                                    if p_stem == expected_stem
                                        || p_text_stem == expected_stem
                                        || &param.text == expected_stem
                                        || &param.pratipadika == expected_stem
                                    {
                                        return Some((**value).clone());
                                    }
                                }
                                None
                            });
                            if let Some(val) = found {
                                ordered.push(val);
                            } else {
                                bail!(
                                    "Missing named argument '{}' in call to UDF '{}'",
                                    expected_stem,
                                    name
                                );
                            }
                        }
                        ordered
                    } else {
                        args.iter()
                            .map(|a| match a {
                                Expression::NamedArg { value, .. } => (**value).clone(),
                                other => other.clone(),
                            })
                            .collect()
                    }
                } else {
                    args.clone()
                };

                let args_sql: Result<Vec<String>> = ordered_args_cow.iter()
                    .map(|arg| self.generate_expression(arg, table_alias, table_context))
                    .collect();
                let mut args_vec = args_sql?;
                // PostgreSQL rounds a double half to even and has no
                // round(double, places); a numeric rounds half away from
                // zero, as SQLite does.
                if self.dialect_name() == "postgres" && name == "सन्निकटनम्" {
                    if let Some(first) = args_vec.first_mut() {
                        *first = format!("CAST({} AS NUMERIC)", first);
                    }
                }
                
                let mut sql = if trans_name.contains("{}") || trans_name.contains("{0}") {
                    self.format_function_template(&trans_name, &args_vec)
                } else if trans_name.contains("(") && args_vec.is_empty() {
                    trans_name.clone()
                } else if args_vec.is_empty() && matches!(trans_name.as_str(), "CURRENT_DATE" | "CURRENT_TIME") {
                    // CURRENT_DATE/CURRENT_TIME are
                    // Postgres keyword literals, not ordinary functions -
                    // unlike now() (which embeds its own parens in the
                    // builtin-table literal above), Postgres rejects
                    // CURRENT_DATE()/CURRENT_TIME() as a syntax error, so
                    // these two must be emitted bare instead of falling
                    // into the generic NAME(args) call-shape below.
                    trans_name.clone()
                } else {
                    let args_str = args_vec.join(", ");
                    format!("{}({})", trans_name, args_str)
                };
                
                if let Some(spec) = window {
                    let mut over_parts = Vec::new();
                    
                    if !spec.partition_by.is_empty() {
                        let partitions: Result<Vec<String>> = spec.partition_by.iter()
                            .map(|e| self.generate_expression(e, table_alias, table_context))
                            .collect();
                        over_parts.push(format!("PARTITION BY {}", partitions?.join(", ")));
                    }
                    
                    if !spec.order_by.is_empty() {
                        let orders: Result<Vec<String>> = spec.order_by.iter()
                            .map(|o| {
                                let expr = self.generate_expression(&o.expr, table_alias, table_context)?;
                                let dir = match o.direction {
                                    crate::ast::OrderDirection::Asc => "ASC",
                                    crate::ast::OrderDirection::Desc => "DESC",
                                };
                                Ok(format!("{} {} NULLS LAST", self.sort_key(expr, &o.expr, table_context), dir))
                            })
                            .collect();
                        over_parts.push(format!("ORDER BY {}", orders?.join(", ")));
                    }

                    if let Some(ref frame) = spec.frame {
                        let units_str = match frame.units {
                            crate::ast::FrameUnits::Rows => "ROWS",
                            crate::ast::FrameUnits::Range => "RANGE",
                            crate::ast::FrameUnits::Groups => "GROUPS",
                        };

                        let mut format_bound = |bound: &crate::ast::FrameBound| -> Result<String> {
                            match bound {
                                crate::ast::FrameBound::UnboundedPreceding => Ok("UNBOUNDED PRECEDING".to_string()),
                                crate::ast::FrameBound::Preceding(e) => {
                                    let expr_sql = self.generate_expression(e, table_alias, table_context)?;
                                    Ok(format!("{} PRECEDING", expr_sql))
                                }
                                crate::ast::FrameBound::CurrentRow => Ok("CURRENT ROW".to_string()),
                                crate::ast::FrameBound::Following(e) => {
                                    let expr_sql = self.generate_expression(e, table_alias, table_context)?;
                                    Ok(format!("{} FOLLOWING", expr_sql))
                                }
                                crate::ast::FrameBound::UnboundedFollowing => Ok("UNBOUNDED FOLLOWING".to_string()),
                            }
                        };

                        let bounds_str = if let Some(ref end_bound) = frame.end {
                            format!(
                                "BETWEEN {} AND {}",
                                format_bound(&frame.start)?,
                                format_bound(end_bound)?
                            )
                        } else {
                            format_bound(&frame.start)?
                        };

                        let exclude_str = if let Some(exclude) = frame.exclude {
                            match exclude {
                                crate::ast::FrameExclude::CurrentRow => " EXCLUDE CURRENT ROW",
                                crate::ast::FrameExclude::Group => " EXCLUDE GROUP",
                                crate::ast::FrameExclude::Ties => " EXCLUDE TIES",
                                crate::ast::FrameExclude::NoOthers => " EXCLUDE NO OTHERS",
                            }
                        } else {
                            ""
                        };

                        over_parts.push(format!("{} {}{}", units_str, bounds_str, exclude_str));
                    }
                    
                    sql.push_str(&format!(" OVER ({})", over_parts.join(" ")));
                }
                
                Ok(sql)
            }
            Expression::Aggregate { expr, func, distinct, .. } => {
                let inner_sql = self.generate_expression(expr, table_alias, table_context)?;
                let inner_sql = self.condition_as_value(expr, inner_sql);
                let distinct_str = if *distinct { "DISTINCT " } else { "" };
                let func_name = func.sql_name();
                let call = format!("{}({}{})", func_name, distinct_str, inner_sql);
                // Postgres SUM/AVG return NUMERIC (arbitrary precision) while SQLite's REAL
                // is always an 8-byte double - cast to DOUBLE PRECISION so both dialects
                // agree on precision.
                if self.dialect_name() == "postgres" && matches!(func, AggFunc::Sum | AggFunc::Avg) {
                    Ok(format!("CAST({} AS DOUBLE PRECISION)", call))
                } else {
                    Ok(call)
                }
            }
            
            Expression::Subquery(dql) => {
                let sql = self.generate_dql_raw(dql)?;
                Ok(format!("({})", sql))
            },
            Expression::SetOp(set_op) => {
                let sql = self.generate_set_op(set_op)?;
                Ok(format!("({})", sql))
            },
            
            Expression::Cast { expr, data_type } => {
                let expr_sql = self.generate_expression(expr, table_alias, table_context)?;
                let postgres = self.dialect_name() == "postgres";
                // A cast to a whole number drops the fraction, as SQLite's
                // does; PostgreSQL's rounds (3.7 → 4).
                let expr_sql = if postgres && data_type == &crate::ast::DataType::Integer {
                    format!("TRUNC(CAST({} AS NUMERIC))", expr_sql)
                } else {
                    expr_sql
                };
                let cast = format!("CAST({} AS {})", expr_sql, self.adaptor.data_type_sql(data_type));
                // Text made by a cast compares as a text column does.
                if postgres && data_type == &crate::ast::DataType::Text {
                    Ok(format!("{} COLLATE \"C\"", cast))
                } else {
                    Ok(cast)
                }
            },
            
            Expression::Wildcard => Ok("*".to_string()),
            // Lowered before codegen; reaching one is a compiler bug, reported
            // as an error rather than a panic.
            Expression::SanskritComparison { .. } => anyhow::bail!("internal error: a comparison reached code generation unlowered"),
            Expression::NamedArg { value, .. } => self.generate_expression(value, table_alias, table_context),
            Expression::Between { expr, low, high, negated } => {
                let expr_sql = self.generate_expression(expr, table_alias, table_context)?;
                let low_sql = self.generate_expression(low, table_alias, table_context)?;
                let high_sql = self.generate_expression(high, table_alias, table_context)?;
                let not = if *negated { "NOT " } else { "" };
                Ok(format!("{} {}BETWEEN {} AND {}", expr_sql, not, low_sql, high_sql))
            }
            Expression::Exists { subquery, negated } => {
                let sub_sql = self.generate_dql_raw(subquery)?;
                if *negated {
                    Ok(format!("NOT EXISTS ({})", sub_sql))
                } else {
                    Ok(format!("EXISTS ({})", sub_sql))
                }
            }
        }
    }
    
    /// Generate CASE expression
    fn generate_case(&mut self, cases: &[CaseArm], table_alias: Option<&str>, table_context: Option<&str>) -> Result<String> {
        let mut parts = vec!["CASE".to_string()];
        
        for arm in cases {
            if let Some(ref cond) = arm.condition {
                let cond_sql = self.generate_expression(cond, table_alias, table_context)?;
                let result_sql = self.generate_expression(&arm.result, table_alias, table_context)?;
                parts.push(format!("WHEN {} THEN {}", cond_sql, result_sql));
            } else {
                // ELSE clause
                let result_sql = self.generate_expression(&arm.result, table_alias, table_context)?;
                parts.push(format!("ELSE {}", result_sql));
            }
        }
        
        parts.push("END".to_string());
        Ok(parts.join(" "))
    }
    pub fn generate_set_op(&mut self, stmt: &crate::ast::SetOpStatement) -> Result<String> {
        let op_str = match (stmt.op.clone(), stmt.use_all || self.is_recursive_cte) {
            (SetOperation::Union, false) => "UNION",
            (SetOperation::Union, true) => "UNION ALL",
            (SetOperation::Intersect, _) => "INTERSECT",
            (SetOperation::Except, _) => "EXCEPT",
        };

        let mut parts = Vec::new();
        for (idx, query_expr) in stmt.queries.iter().enumerate() {
            if self.is_recursive_cte {
                self.recursive_member_idx = Some(idx);
            }
            if let Expression::Identifier(ident) = query_expr {
                 let table_name = self.resolve_table(ident)?;
                 parts.push(format!("SELECT * FROM {}", table_name));
            } else if let Expression::SetOp(inner) = query_expr {
                 // A nested set operation keeps its grouping as a derived
                 // table: emitted flat, `(A ∪ B) ∩ C` and `A ∪ (B ∩ C)` would
                 // compile alike, and SQLite does not accept parentheses
                 // around a compound-select member.
                 let inner_sql = self.generate_set_op(inner)?;
                 let alias = self.next_alias();
                 parts.push(format!("SELECT * FROM ({}) AS {}", inner_sql, alias));
            } else {
                 let sql = self.generate_expression(query_expr, None, None)?;
                 let sql_trimmed = sql.trim();
                 let sql_clean = if sql_trimmed.starts_with('(') && sql_trimmed.ends_with(')') {
                     sql_trimmed[1..sql_trimmed.len()-1].trim().to_string()
                 } else {
                     sql_trimmed.to_string()
                 };
                 parts.push(sql_clean);
            }
            self.recursive_member_idx = None;
        }

        Ok(parts.join(&format!(" {} ", op_str)))
    }
    pub fn generate_dml(&mut self, dml: &crate::ast::DmlStatement) -> Result<String> {
        match dml {
            crate::ast::DmlStatement::Delete { table, where_clause } => {
                let sql_table = self.resolve_table(table)?;
                let table_stem = self.resolve_table_stem(table);
                self.in_table_scope(&table_stem, |gen| match where_clause {
                    // Pass table stem as context so columns like "Sankhya" resolve correctly
                    Some(w) => {
                        let condition = gen.generate_expression(&w.condition, None, Some(&table_stem))?;
                        Ok(format!("DELETE FROM {} WHERE {};", sql_table, condition))
                    }
                    None => Ok(format!("DELETE FROM {};", sql_table)),
                })
            },
            crate::ast::DmlStatement::Update { table, where_clause, set_clause, .. } => {
                let sql_table = self.resolve_table(table)?;
                let table_stem = self.resolve_table_stem(table);
                
                // One `col = value` per assignment; several form a च-list
                // (an AND chain in the AST), emitted comma-separated.
                fn assignment_items<'e>(expr: &'e Expression, out: &mut Vec<&'e Expression>) {
                    match expr {
                        Expression::LogicalOp { left, op: crate::ast::LogicalOperator::And, right } => {
                            assignment_items(left, out);
                            assignment_items(right, out);
                        }
                        other => out.push(other),
                    }
                }
                self.in_table_scope(&table_stem, |gen| {
                    let mut items = Vec::new();
                    assignment_items(&set_clause.assignments, &mut items);
                    // `col = value` written directly: as a comparison, a NULL
                    // value would become `col IS NULL`.
                    let assignments = items
                        .into_iter()
                        .map(|a| match a {
                            Expression::BinaryOp { left, op: crate::ast::BinaryOperator::Equal, right } => {
                                if let (Expression::Identifier(column), Expression::Literal(crate::ast::Literal::Null)) = (&**left, &**right) {
                                    gen.check_may_be_empty(column, &table_stem)?;
                                }
                                Ok(format!(
                                    "{} = {}",
                                    gen.generate_expression(left, None, Some(&table_stem))?,
                                    gen.generate_expression(right, None, Some(&table_stem))?
                                ))
                            }
                            other => gen.generate_expression(other, None, Some(&table_stem)),
                        })
                        .collect::<Result<Vec<_>>>()?
                        .join(", ");
                
                    match where_clause {
                        Some(w) => {
                            let condition = gen.generate_expression(&w.condition, None, Some(&table_stem))?;
                            Ok(format!("UPDATE {} SET {} WHERE {};", sql_table, assignments, condition))
                        }
                        None => Ok(format!("UPDATE {} SET {};", sql_table, assignments)),
                    }
                })
            },
            crate::ast::DmlStatement::Insert { table, values, .. } => {
                let sql_table = self.resolve_table(table)?;
                let table_stem = self.resolve_table_stem(table);
                
                // Helper to collect assignments from the folded expression tree
                let mut assignments = Vec::new();
                fn collect_pairs<'a>(expr: &'a Expression, list: &mut Vec<(&'a Identifier, &'a Expression)>) -> Result<()> {
                    match expr {
                         Expression::LogicalOp { left, op, right } => {
                             if *op != LogicalOperator::And {
                                 bail!("INSERT expects AND connected pairs");
                             }
                             collect_pairs(left, list)?;
                             collect_pairs(right, list)?;
                             Ok(())
                         },
                         Expression::BinaryOp { left, op, right } => {
                             if *op != BinaryOperator::Equal {
                                 bail!("INSERT expects Equality (Col=Val) pairs");
                             }
                             if let Expression::Identifier(col) = left.as_ref() {
                                 list.push((col, right));
                                 Ok(())
                             } else {
                                bail!("INSERT Left side must be Identifier");
                             }
                         },
                         Expression::Wildcard => Ok(()), // Ignore fillers
                         _ => bail!("Invalid expression structure for INSERT values"),
                    }
                }
                
                collect_pairs(values, &mut assignments)?;
                
                let mut cols = Vec::new();
                let mut vals = Vec::new();
                
                for (col_ident, val_expr) in assignments {
                    if matches!(val_expr, Expression::Literal(crate::ast::Literal::Null)) {
                        self.check_may_be_empty(col_ident, &table_stem)?;
                    }
                    let col_name = self.resolve_column(col_ident, Some(&table_stem))?;
                    let val_sql = self.generate_expression(val_expr, None, None)?;
                    cols.push(col_name);
                    vals.push(val_sql);
                }
                
                Ok(format!("INSERT INTO {} ({}) VALUES ({});", sql_table, cols.join(", "), vals.join(", ")))
            },
            crate::ast::DmlStatement::InsertSelect { table, columns, query, .. } => {
                let sql_table = self.resolve_table(table)?;
                let table_stem = self.resolve_table_stem(table);
                
                let cols_str = if let Some(cols) = columns {
                    let col_names: Result<Vec<String>> = cols.iter()
                        .map(|c| self.resolve_column(c, Some(&table_stem)))
                        .collect();
                    format!(" ({})", col_names?.join(", "))
                } else {
                    "".to_string()
                };
                
                let select_sql = self.generate_dql_raw(query)?;
                Ok(format!("INSERT INTO {}{} {};", sql_table, cols_str, select_sql))
            }
        }
    }

    pub fn generate_explain(&mut self, stmt: &crate::ast::Statement) -> Result<String> {
         // Generate inner SQL (without semicolon)
         let inner_sql = match stmt {
             crate::ast::Statement::Dql(dql) => self.generate_dql_raw(dql)?,
             crate::ast::Statement::SetOp(set) => self.generate_set_op(set)?,
             crate::ast::Statement::Dml(dml) => {
                 let dml_sql = self.generate_dml(dml)?;
                 // Remove trailing semicolon if present
                 dml_sql.trim_end_matches(';').trim().to_string()
             },
             _ => bail!("Unsupported statement type for EXPLAIN"),
         };
         
         // Use generic EXPLAIN or dialect specific?
         // SQLite supports "EXPLAIN QUERY PLAN"
         // Postgres supports "EXPLAIN"
         if self.adaptor.name() == "sqlite" {
             Ok(format!("EXPLAIN QUERY PLAN {};", inner_sql))
         } else {
             Ok(format!("EXPLAIN {};", inner_sql))
         }
    }

    pub fn generate_ddl(&mut self, ddl: &crate::ast::DdlStatement) -> Result<String> {
        match ddl {
            crate::ast::DdlStatement::Create(create_stmt) => {
                let pratipadika = create_stmt.type_name.pratipadika.as_str();
                let obj_type = match pratipadika {
                    "सारणी" | "पटल" => "TABLE",
                    "दृश्यम्" | "दृश्य" | "कल्पितपटल" | "कल्पितपटलम्" => "VIEW",
                    _ => "TABLE", // Default
                };
                
                let table_name = create_stmt.sql_name.as_deref().unwrap_or(&create_stmt.name.pratipadika);

                // A second Sanskrit name deliberately declared for a
                // physical table already created earlier in this batch
                // (see the `created_tables` doc comment) - the schema
                // registration for this name already happened in
                // Schema::update_from_ddl before codegen ever runs, so
                // skip re-emitting CREATE TABLE for it.
                if obj_type == "TABLE" {
                    if !self.created_tables.insert(table_name.to_string()) {
                        return Ok("".to_string());
                    }
                }

                let mut sql = if obj_type == "VIEW" {
                    self.adaptor.emit_create_view(table_name, create_stmt.is_temporary, false)
                } else {
                    self.adaptor.emit_create_table(table_name, create_stmt.is_temporary, false)
                };
                
                if !create_stmt.columns.is_empty() {
                    let cols: Vec<String> = create_stmt.columns.iter()
                        .map(|col| {
                            let col_name = col.sql_name.as_deref().unwrap_or(&col.name.pratipadika);
                            self.adaptor.emit_column_def(
                                col_name,
                                &col.data_type,
                                &col.constraints,
                                &|ident| Ok((self.resolve_table(ident)?, self.resolve_table_pk(ident)))
                            )
                        })
                        .collect::<Result<Vec<String>>>()?;
                    sql.push_str(" (\n    ");
                    sql.push_str(&cols.join(",\n    "));
                    sql.push_str("\n)");
                } else if let Some(query) = &create_stmt.query {
                    // CREATE VIEW AS ...
                    sql.push_str(" AS\n");
                    // We need to generate the inner statement. 
                    // create_stmt.query is a Box<Statement>.
                    // But we don't have a generate_statement public method easily accessible recursively?
                    // We can match it manually.
                    match query.as_ref() {
                         crate::ast::Statement::Dql(dql) => {
                             sql.push_str(&self.generate_dql_raw(dql)?);
                         },
                         crate::ast::Statement::SetOp(set) => {
                             sql.push_str(&self.generate_set_op(set)?);
                         },
                         _ => bail!("Unsupported statement type for CREATE AS"),
                    }
                }
                
                Ok(format!("{};\n", sql))
            }
            crate::ast::DdlStatement::Drop(drop_stmt) => {
                let obj_type = match drop_stmt.type_name.pratipadika.as_str() {
                    "सारणी" | "पटल" => "TABLE",
                    "दृश्यम्" | "दृश्य" | "कल्पितपटल" | "कल्पितपटलम्" => "VIEW",
                    _ => "TABLE", // Default
                };
                // Deliberately lenient: dropping a table or view that isn't tracked in
                // the schema (e.g., an IF EXISTS drop of an external or non-existent object)
                // falls back to the stem name.
                let resolved_name = self.resolve_table(&drop_stmt.name).unwrap_or_else(|_| drop_stmt.name.pratipadika.clone());
                let exists_str = if drop_stmt.is_exists_check { "IF EXISTS " } else { "" };
                Ok(format!("DROP {} {}{};\n", obj_type, exists_str, resolved_name))
            }
            crate::ast::DdlStatement::CreateIndex(create_idx) => {
                let table_name = self.resolve_table(&create_idx.table_name)?;
                let index_name = create_idx.name.pratipadika.clone();
                let columns: Vec<(String, Option<crate::codegen::traits::OrderDirection>)> = create_idx.columns.iter().map(|col| {
                    let col_name = self.resolve_column(&col.name, Some(&create_idx.table_name.pratipadika))?;
                    let dir = col.direction.map(|d| match d {
                        crate::ast::OrderDirection::Asc => crate::codegen::traits::OrderDirection::Asc,
                        crate::ast::OrderDirection::Desc => crate::codegen::traits::OrderDirection::Desc,
                    });
                    Ok((col_name, dir))
                }).collect::<Result<Vec<_>>>()?;
                let sql = self.adaptor.emit_create_index(&index_name, &table_name, &columns, create_idx.is_unique, create_idx.if_not_exists);
                Ok(format!("{};\n", sql))
            }
            crate::ast::DdlStatement::DropIndex(drop_idx) => {
                let index_name = drop_idx.name.pratipadika.clone();
                let sql = self.adaptor.emit_drop_index(&index_name, drop_idx.is_exists_check);
                Ok(format!("{};\n", sql))
            }
            crate::ast::DdlStatement::AlterTable(alter_stmt) => {
                let table_name = self.resolve_table(&alter_stmt.table_name)?;
                let sql = match &alter_stmt.action {
                    crate::ast::AlterAction::AddColumn(column_def) => {
                        let col_name = column_def.sql_name.as_deref().unwrap_or(&column_def.name.pratipadika);
                        // ADD COLUMN reads sql_name straight off the AST rather than
                        // through Schema::update_from_ddl, so it needs its own check -
                        // see schema::validate_sql_identifier's doc comment.
                        crate::schema::validate_sql_identifier(col_name, &format!("column \"{}\" of table \"{}\"", column_def.name.text, alter_stmt.table_name.text))?;
                        let col_def_sql = self.adaptor.emit_column_def(
                            col_name,
                            &column_def.data_type,
                            &column_def.constraints,
                            &|ident| Ok((self.resolve_table(ident)?, self.resolve_table_pk(ident)))
                        )?;
                        self.adaptor.emit_alter_table_add_column(&table_name, &col_def_sql)
                    }
                    crate::ast::AlterAction::DropColumn(col_name) => {
                        let column = self.resolve_column(col_name, Some(&alter_stmt.table_name.pratipadika))?;
                        self.adaptor.emit_alter_table_drop_column(&table_name, &column)
                    }
                    crate::ast::AlterAction::RenameColumn { old_name, new_name } => {
                        let old = self.resolve_column(old_name, Some(&alter_stmt.table_name.pratipadika))?;
                        let new = new_name.pratipadika.clone();
                        self.adaptor.emit_alter_table_rename_column(&table_name, &old, &new)
                    }
                    crate::ast::AlterAction::RenameTable(new_table_name) => {
                        let new = new_table_name.pratipadika.clone();
                        self.adaptor.emit_alter_table_rename_table(&table_name, &new)
                    }
                };
                Ok(format!("{};\n", sql))
            }
            crate::ast::DdlStatement::CreateUdf(_) => Ok("".to_string()),
        }
    }

    pub fn generate_tcl(&mut self, tcl: &crate::ast::TclStatement) -> Result<String> {
        match tcl {
            crate::ast::TclStatement::Begin => Ok("BEGIN;".to_string()),
            crate::ast::TclStatement::Commit => Ok("COMMIT;".to_string()),
            crate::ast::TclStatement::Rollback { savepoint } => {
                if let Some(sp) = savepoint {
                    Ok(format!("ROLLBACK TO SAVEPOINT {};", sp.pratipadika))
                } else {
                    Ok("ROLLBACK;".to_string())
                }
            },
            crate::ast::TclStatement::Savepoint { name } => {
                Ok(format!("SAVEPOINT {};", name.pratipadika))
            }
        }
    }
}

/// Binding strength of an arithmetic operator (None for anything else).
fn arithmetic_precedence(op: &crate::ast::BinaryOperator) -> Option<u8> {
    use crate::ast::BinaryOperator::*;
    match op {
        Add | Subtract => Some(1),
        Multiply | Divide => Some(2),
        _ => None,
    }
}

/// Whether `operand` of an arithmetic `op` must be bracketed in SQL to keep
/// the AST's grouping.
fn arithmetic_operand_needs_parens(op: &crate::ast::BinaryOperator, operand: &Expression, is_right: bool) -> bool {
    let (Some(parent), Expression::BinaryOp { op: child_op, .. }) = (arithmetic_precedence(op), operand) else {
        return false;
    };
    let Some(child) = arithmetic_precedence(child_op) else {
        return false;
    };
    // A right operand at the same precedence keeps its brackets unless it
    // repeats an associative operator (a + (b + c), a * (b * c)): integer
    // division makes a * (b / c) differ from a * b / c, and floating point
    // makes a + (b - c) differ from a + b - c.
    use crate::ast::BinaryOperator::{Add, Multiply};
    let associative_repeat = child_op == op && matches!(op, Add | Multiply);
    child < parent || (is_right && child == parent && !associative_repeat)
}

