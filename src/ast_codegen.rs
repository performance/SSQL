    #[test]
    fn test_devanagari_date_literal_normalization() {
        let schema = make_schema();
        let adaptor = SQLiteAdaptor::new();
        let mut codegen = AstCodeGen::new(&adaptor, &schema, vec![]);

        let date_expr = Expression::Literal(Literal::String("२०२३-१०-०१".to_string()));
        let sql = codegen.generate_expression(&date_expr, None, None).unwrap();
        assert_eq!(sql, "'2023-10-01'");

        let non_date_expr = Expression::Literal(Literal::String("अध्यायः १".to_string()));
        let non_date_sql = codegen.generate_expression(&non_date_expr, None, None).unwrap();
        assert_eq!(non_date_sql, "'अध्यायः १'");
    }
